    public async Task<MarketplaceOrderAllocationResult> CreateHeldOrderAsync(
        Guid tenantId,
        string checkoutIdempotencyKey,
        MarketplaceOrderAllocationInput input,
        CancellationToken token)
    {
        if (!await features.IsEnabledAsync(tenantId, FeatureKeys.MarketplaceCheckout, token))
            throw new BusinessRuleException("Marketplace checkout is not currently available.");
        var key = checkoutIdempotencyKey?.Trim();
        if (tenantId == Guid.Empty || string.IsNullOrWhiteSpace(key) || key.Length > 160)
            throw new BusinessRuleException("A tenant and valid checkout idempotency key are required.");
        var address = input.DeliveryAddressSnapshot?.Trim();
        var pincode = input.Pincode?.Trim();
        if (string.IsNullOrWhiteSpace(address) || address.Length > 1000 || !PincodeRegex().IsMatch(pincode ?? string.Empty))
            throw new BusinessRuleException("Enter a valid delivery address and pincode.");
        if (input.ReservationExpiresAt <= DateTimeOffset.UtcNow)
            throw new BusinessRuleException("The inventory reservation expiry must be in the future.");

        if (string.IsNullOrWhiteSpace(input.CatalogueItemsJson) || input.ExpectedPayableAmount < 0)
            throw new BusinessRuleException("The authoritative order total could not be verified.");
        var executionInput = input with { DeliveryAddressSnapshot = address, Pincode = pincode! };
        // Reservation expiry is generated by the server per request and must not make
        // a retry with the same checkout key look like a different customer order.
        var fingerprintInput = executionInput with { ReservationExpiresAt = DateTimeOffset.UnixEpoch };
        var envelope = new CreateEnvelope(tenantId, key, fingerprintInput);
        try
        {
            return await idempotency.ExecuteForTenant(key, "MARKETPLACE_ORDER_RESERVE", envelope,
                input.Invoice.User, tenantId,
                (connection, transaction, ct) => CreateInTransaction(connection, transaction, tenantId, key, executionInput, ct), token);
        }
        catch (SqlException ex) when (ex.Number >= 51100)
        {
            throw new BusinessRuleException(ex.Message);
        }
    }

    private async Task<MarketplaceOrderAllocationResult> CreateInTransaction(
        SqlConnection connection, SqlTransaction transaction, Guid tenantId, string checkoutKey,
        MarketplaceOrderAllocationInput input, CancellationToken token)
    {
        if (!await features.IsEnabledAsync(tenantId, FeatureKeys.MarketplaceCheckout, token))
            throw new BusinessRuleException("Marketplace checkout is not currently available.");
        var request = input.Invoice;
        if (request.CustomerId is null || request.TenantId is Guid requestTenant && requestTenant != tenantId)
            throw new BusinessRuleException("A tenant-matched customer is required for a marketplace order.");
        if (request.AppliedPromotionId is not null && request.CustomerId is null)
            throw new BusinessRuleException("A customer is required for the selected offer.");
        var items = DeserializeItems(request.ItemsJson);
        if (items.Count == 0 || items.Select(x => x.ProductId).Distinct().Count() != items.Count
            || items.Any(x => x.Quantity <= 0 || x.UnitPrice < 0 || x.TaxPercentage < 0))
            throw new BusinessRuleException("Refresh the cart and review its quantities and prices.");
        var catalogueItems = DeserializeItems(input.CatalogueItemsJson);
        if (catalogueItems.Count != items.Count || catalogueItems.Select(x => x.ProductId).Distinct().Count() != catalogueItems.Count
            || items.Any(x => !catalogueItems.Any(c => c.ProductId == x.ProductId && c.Quantity == x.Quantity)))
            throw new BusinessRuleException("The cart changed while checkout was being prepared. Refresh and try again.");
        if (input.ReservationExpiresAt <= DateTimeOffset.UtcNow)
            throw new BusinessRuleException("The cart reservation window has expired. Please try again.");

        await RevalidateCatalogueAndPricing(connection, transaction, tenantId, input.CatalogueItemsJson, token);
        await RevalidatePromotion(connection, transaction, tenantId, request, token);
        var plan = await BuildAllocationPlan(connection, transaction, tenantId, items, input.Pincode, token);
        if (plan.Count == 0) throw new BusinessRuleException("No eligible warehouse stock is available for this order.");

        var firstWarehouse = plan.OrderBy(x => x.ProductId).ThenBy(x => x.WarehouseId).First().WarehouseId;
        var invoice = await PostHeldInvoice(connection, transaction, tenantId,
            request with { WarehouseId = firstWarehouse, Status = "HELD", PaymentsJson = "[]", TenantId = tenantId, SourceChannel = null, ServicePincode = input.Pincode }, token);
        if (invoice.GrandTotal != input.ExpectedPayableAmount)
            throw new BusinessRuleException("The order total has changed. Please review the updated amount and confirm again.");

        await using (var classify = new SqlCommand("UPDATE sales.SalesInvoices SET OrderType='MARKETPLACE' WHERE TenantId=@tenant AND InvoiceId=@order AND Status='HELD' AND OrderType='STANDARD';", connection, transaction))
        {
            classify.Parameters.AddWithValue("@tenant", tenantId);
            classify.Parameters.AddWithValue("@order", invoice.InvoiceId);
            if (await classify.ExecuteNonQueryAsync(token) != 1)
                throw new BusinessRuleException("The marketplace invoice could not be safely classified.");
        }
        await using (var marketplace = new SqlCommand("INSERT commerce.MarketplaceOrders(TenantId,OrderId,OrderKind,LifecycleStatus,CheckoutIdempotencyKey,ReservationExpiresAt) VALUES(@tenant,@order,'MARKETPLACE','DRAFT',@key,@expires);", connection, transaction))
        {
            marketplace.Parameters.AddWithValue("@tenant", tenantId);
            marketplace.Parameters.AddWithValue("@order", invoice.InvoiceId);
            marketplace.Parameters.AddWithValue("@key", checkoutKey);
            marketplace.Parameters.AddWithValue("@expires", input.ReservationExpiresAt);
            await marketplace.ExecuteNonQueryAsync(token);
        }

        await AddStorefrontSource(connection, transaction, tenantId, invoice.InvoiceId, input.DeliveryAddressSnapshot,
            input.Pincode, request.CustomerId.Value, request.User, token);
        await AddPromotionUse(connection, transaction, tenantId, invoice.InvoiceId, request, token);

        var invoiceItems = await ReadInvoiceItems(connection, transaction, invoice.InvoiceId, token);
        var lineMap = invoiceItems.ToDictionary(x => x.ProductId);
        if (lineMap.Count != items.Count || items.Any(x => !lineMap.ContainsKey(x.ProductId)))
            throw new BusinessRuleException("The invoice lines could not be reconciled to the marketplace cart.");

        var groups = BuildGroups(plan);
        foreach (var group in groups)
        {
            await InsertGroup(connection, transaction, tenantId, invoice.InvoiceId, group, input.DeliveryAddressSnapshot, token);
        }

        var savedAllocations = new List<SavedAllocation>(plan.Count);
        foreach (var chunk in plan.OrderBy(x => x.WarehouseId).ThenBy(x => x.ProductId)
                     .ThenBy(x => x.ZoneId).ThenBy(x => x.BinId).ThenBy(x => x.BatchNo).ThenBy(x => x.SerialNo))
        {
            var line = lineMap[chunk.ProductId];
            var allocationId = Guid.NewGuid();
            await InsertAllocation(connection, transaction, tenantId, invoice.InvoiceId, line.InvoiceItemId,
                allocationId, chunk, token);
            savedAllocations.Add(new(allocationId, line.InvoiceItemId, chunk));
        }

        foreach (var saved in savedAllocations.OrderBy(x => x.Plan.WarehouseId).ThenBy(x => x.Plan.ProductId).ThenBy(x => x.AllocationId))
            await ReserveAllocation(connection, transaction, tenantId, saved.AllocationId,
                input.ReservationExpiresAt, request.User, token);

        var groupIds = groups.ToDictionary(x => x.Key, x => x.GroupId);
        foreach (var saved in savedAllocations)
        {
            var groupId = groupIds[saved.Plan.GroupKey];
            await InsertGroupItem(connection, transaction, tenantId, groupId, saved.AllocationId, token);
        }

        // Supplier liability drafts are part of the same atomic parent-order write.
        // GuturGo-owned allocations are intentionally omitted by the writer.
        await MarketplacePartnerSettlementWriter.CreateDraftsAsync(connection, transaction,
            tenantId, invoice.InvoiceId, request.User ?? "STOREFRONT", token);

        await using (var activate = new SqlCommand("UPDATE commerce.MarketplaceOrders SET LifecycleStatus='RESERVED',UpdatedAt=SYSUTCDATETIME() WHERE TenantId=@tenant AND OrderId=@order AND LifecycleStatus='DRAFT';", connection, transaction))
        {
            activate.Parameters.AddWithValue("@tenant", tenantId);
            activate.Parameters.AddWithValue("@order", invoice.InvoiceId);
            if (await activate.ExecuteNonQueryAsync(token) != 1)
                throw new BusinessRuleException("The marketplace allocations could not be finalized.");
        }

        var receipts = groups.Select(group => new MarketplaceFulfilmentAllocationGroup(
            group.GroupId, group.GroupNumber, group.WarehouseId, group.SellerKind, group.PartnerSellerId,
            savedAllocations.Where(x => x.Plan.GroupKey == group.Key)
                .GroupBy(x => x.Plan.ProductId)
                .Select(x => new MarketplaceAllocatedItem(x.Key, x.Sum(y => y.Plan.Quantity)))
                .OrderBy(x => x.ProductId).ToArray())).ToArray();
        return new(invoice.InvoiceId, invoice.InvoiceNumber, invoice.GrandTotal, "HELD", receipts);
    }

    public async Task<MarketplaceAllocationEligibilityResult> CheckAvailabilityAsync(
        Guid tenantId, IReadOnlyCollection<StorefrontCheckoutItem> items, string pincode, CancellationToken token)
    {
        var normalizedPincode = pincode?.Trim() ?? string.Empty;
        if (tenantId == Guid.Empty || !PincodeRegex().IsMatch(normalizedPincode))
            return new(false, "DELIVERY_DETAILS_REQUIRED", "Enter a valid delivery pincode to check item availability.");
        if (!await features.IsEnabledAsync(tenantId, FeatureKeys.MarketplaceCheckout, token))
            return new(false, "MARKETPLACE_CHECKOUT_DISABLED", "Marketplace checkout is not currently available.");
        var normalized = (items ?? []).GroupBy(x => x.ProductId)
            .Select(x => new StorefrontCheckoutItem(x.Key, x.Sum(y => y.Quantity))).ToArray();
        if (normalized.Length is 0 or > 100 || normalized.Any(x => x.ProductId == Guid.Empty || x.Quantity <= 0 || x.Quantity > 9999))
            return new(false, "INVALID_CART", "The cart contains invalid items or quantities.");

        await using var connection = new SqlConnection(ConnectionString);
        await connection.OpenAsync(token);
        await using (var context = new SqlCommand("EXEC sys.sp_set_session_context @key=N'TenantId',@value=@tenant;", connection))
        { context.Parameters.AddWithValue("@tenant", tenantId); await context.ExecuteNonQueryAsync(token); }
        await using var transaction = (SqlTransaction)await connection.BeginTransactionAsync(IsolationLevel.Serializable, token);
        try
        {
            var allocationItems = normalized.Select(x => new POSItemInput(x.ProductId, null, x.Quantity, 0, 0, 0, 0)).ToArray();
            var plan = await BuildAllocationPlan(connection, transaction, tenantId, allocationItems, normalizedPincode, token);
            await transaction.CommitAsync(token);
            return plan.Count == 0
                ? new(false, "NO_ELIGIBLE_STOCK", "These items cannot currently be fulfilled for this delivery address.")
                : new(true, MayArriveSeparately: plan.Select(x => x.GroupKey).Distinct().Count() > 1);
        }
        catch (BusinessRuleException error)
        {
            await transaction.RollbackAsync(CancellationToken.None);
            return new(false, "NO_ELIGIBLE_STOCK", error.Message);
        }
        catch
        {
            await transaction.RollbackAsync(CancellationToken.None);
            throw;
        }
    }

    private static async Task RevalidateCatalogueAndPricing(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, string itemsJson, CancellationToken token)
    {
        await using var command = new SqlCommand("""
            DECLARE @ids TABLE(ProductId uniqueidentifier PRIMARY KEY);
            INSERT @ids SELECT DISTINCT ProductId FROM OPENJSON(@items) WITH(ProductId uniqueidentifier '$.ProductId');
            DECLARE @locked bigint;
            SELECT @locked=COUNT_BIG(*) FROM master.Products p WITH(UPDLOCK,HOLDLOCK)
                JOIN @ids i ON i.ProductId=p.ProductId WHERE p.TenantId=@tenant;
            SELECT @locked=COUNT_BIG(*) FROM commerce.ProductPublications a WITH(UPDLOCK,HOLDLOCK)
                JOIN @ids i ON i.ProductId=a.ProductId WHERE a.TenantId=@tenant;
            SELECT @locked=COUNT_BIG(*) FROM master.ProductImages a WITH(HOLDLOCK)
                JOIN @ids i ON i.ProductId=a.ProductId WHERE a.TenantId=@tenant;
            SELECT @locked=COUNT_BIG(*) FROM master.ProductSpecifications a WITH(HOLDLOCK)
                JOIN @ids i ON i.ProductId=a.ProductId WHERE a.TenantId=@tenant;
            IF EXISTS(SELECT 1 FROM @ids i WHERE NOT EXISTS(
                SELECT 1 FROM master.Products p WHERE p.TenantId=@tenant AND p.ProductId=i.ProductId
                  AND p.IsActive=1 AND p.IsDeleted=0 AND p.IsWhatsAppVisible=1
                  AND commerce.IsProductPubliclyApproved(@tenant,p.ProductId)=1
                  AND EXISTS(SELECT 1 FROM master.TenantProductCategories x WHERE x.TenantId=@tenant AND x.ProductCategoryId=p.CategoryId)
                  AND EXISTS(SELECT 1 FROM master.ProductCategories x WHERE x.ProductCategoryId=p.CategoryId AND x.IsActive=1 AND x.IsDeleted=0)
                  AND EXISTS(SELECT 1 FROM master.TenantUnitsOfMeasure x WHERE x.TenantId=@tenant AND x.UnitId=p.UnitId)
                  AND EXISTS(SELECT 1 FROM master.UnitsOfMeasure x WHERE x.UnitId=p.UnitId AND x.IsActive=1 AND x.IsDeleted=0)))
                THROW 51100,'One or more cart items are no longer available for storefront ordering.',1;
            IF EXISTS(SELECT 1 FROM OPENJSON(@items) WITH(ProductId uniqueidentifier '$.ProductId',UnitPrice decimal(18,4) '$.UnitPrice',TaxPercentage decimal(18,4) '$.TaxPercentage') j
                JOIN master.Products p WITH(UPDLOCK,HOLDLOCK) ON p.TenantId=@tenant AND p.ProductId=j.ProductId
                WHERE p.SellingPrice<>j.UnitPrice OR p.GSTPercentage<>j.TaxPercentage)
                THROW 51100,'A product price or tax changed. Refresh your cart and try again.',1;
            """, connection, transaction);
        command.Parameters.AddWithValue("@tenant", tenantId);
        command.Parameters.AddWithValue("@items", itemsJson);
        await command.ExecuteNonQueryAsync(token);
    }

    private static async Task RevalidatePromotion(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, POSPostRequest request, CancellationToken token)
    {
        if (request.AppliedPromotionId is not Guid promotionId) return;
        if (request.CustomerId is not Guid customerId)
            throw new BusinessRuleException("An authenticated customer is required for this offer.");
        await using var customerLock = new SqlCommand("SELECT CustomerId FROM sales.Customers WITH(UPDLOCK,HOLDLOCK) WHERE TenantId=@tenant AND CustomerId=@customer AND IsActive=1 AND IsDeleted=0;", connection, transaction);
        customerLock.Parameters.AddWithValue("@tenant", tenantId);
        customerLock.Parameters.AddWithValue("@customer", customerId);
        if (await customerLock.ExecuteScalarAsync(token) is not Guid)
            throw new BusinessRuleException("Customer is no longer available.");
        await using var eligibility = new SqlCommand("""
            SELECT p.OfferType,p.UsageLimitPerCustomer,
              (SELECT COUNT(1) FROM commerce.StorefrontPromotionUses u
               JOIN sales.SalesInvoices i ON i.InvoiceId=u.InvoiceId AND i.TenantId=u.TenantId
               OUTER APPLY(SELECT TOP(1) cp.Status FROM commerce.CommercePayments cp WHERE cp.TenantId=i.TenantId AND cp.InvoiceId=i.InvoiceId ORDER BY cp.AttemptNumber DESC) payment
               WHERE u.TenantId=@tenant AND u.PromotionId=p.PromotionId AND u.CustomerId=@customer
                 AND i.Status NOT IN(N'CANCELLED',N'VOID') AND (i.Status=N'COMPLETED' OR payment.Status IS NULL OR payment.Status<>N'FAILED')),
              (SELECT COUNT(1) FROM sales.SalesInvoices i
               JOIN integration.WhatsAppCommerceOrders w ON w.InvoiceId=i.InvoiceId AND w.TenantId=i.TenantId AND w.SourceChannel=N'STOREFRONT'
               WHERE i.TenantId=@tenant AND i.CustomerId=@customer AND i.Status=N'COMPLETED')
            FROM commerce.StorefrontPromotions p WITH(UPDLOCK,HOLDLOCK)
            WHERE p.TenantId=@tenant AND p.PromotionId=@promotion AND p.IsDeleted=0 AND p.IsActive=1
              AND (p.StartsAt IS NULL OR p.StartsAt<=SYSUTCDATETIME())
              AND (p.EndsAt IS NULL OR p.EndsAt>SYSUTCDATETIME());
            """, connection, transaction);
        eligibility.Parameters.AddWithValue("@tenant", tenantId);
        eligibility.Parameters.AddWithValue("@customer", customerId);
        eligibility.Parameters.AddWithValue("@promotion", promotionId);
        await using var reader = await eligibility.ExecuteReaderAsync(token);
        if (!await reader.ReadAsync(token))
            throw new BusinessRuleException("The offer is no longer available. Refresh your cart.");
        var offerType = reader.GetString(0);
        var usageLimit = reader.IsDBNull(1) ? (int?)null : reader.GetInt32(1);
        var previousUses = reader.GetInt32(2);
        var completedOrders = reader.GetInt32(3);
        if (usageLimit is not null && previousUses >= usageLimit.Value
            || offerType == "FIRST_ORDER" && (previousUses > 0 || completedOrders > 0))
            throw new BusinessRuleException("The offer is no longer available. Refresh your cart.");
    }

    private async Task<List<PlannedAllocation>> BuildAllocationPlan(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, IReadOnlyCollection<POSItemInput> items, string pincode, CancellationToken token)
    {
        var result = new List<PlannedAllocation>();
        foreach (var item in items.OrderBy(x => x.ProductId))
        {
            var seller = await ResolveSeller(connection, transaction, tenantId, item.ProductId, token);
            if (seller.SellerKind == "PARTNER")
            {
                if (!await features.IsEnabledAsync(tenantId, FeatureKeys.PartnerCommissions, token))
                    throw new BusinessRuleException("Partner products require an enabled commercial agreement capability.");
                seller = seller with { Agreement = await ReadActiveAgreement(connection, transaction, tenantId, seller, item.ProductId, token) };
            }
            var candidates = await ReadCandidateWarehouses(connection, transaction, tenantId, seller, pincode, token);
            var stockCandidates = new List<MarketplaceStockCandidate>();
            decimal eligibleQuantity = 0;
            foreach (var warehouseId in candidates)
            {
                var eligibility = await warehouseEligibility.CheckWithinTransactionAsync(
                    new(tenantId, warehouseId, item.ProductId, seller.SellerKind, seller.PartnerSellerId, pincode, seller.MarketplaceCityId),
                    connection, transaction, token);
                if (!eligibility.IsEligible) continue;
                var balances = await ReadAvailableBalances(connection, transaction, tenantId, warehouseId, item.ProductId, token);
                foreach (var balance in balances)
                {
                    stockCandidates.Add(new(warehouseId, balance.ZoneId, balance.BinId, balance.BatchNo, balance.SerialNo, balance.AvailableQuantity));
                    eligibleQuantity += balance.AvailableQuantity;
                }
                if (eligibleQuantity >= item.Quantity) break;
            }
            var allocated = MarketplaceWarehouseAllocationPolicy.Allocate(item.Quantity, stockCandidates);
            result.AddRange(allocated.Select(x => new PlannedAllocation(item.ProductId, x.WarehouseId, x.Quantity,
                seller.SellerKind, seller.PartnerSellerId, seller.Agreement, x.ZoneId, x.BinId, x.BatchNo, x.SerialNo)));
        }
        return result;
    }

    private static async Task<SellerSource> ResolveSeller(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, Guid productId, CancellationToken token)
    {
        await using var command = new SqlCommand("SELECT l.PartnerSellerId,l.ListingStatus,s.CityId FROM commerce.PartnerProductListings l WITH(UPDLOCK,HOLDLOCK) JOIN commerce.PartnerSellers s WITH(UPDLOCK,HOLDLOCK) ON s.OperatingTenantId=l.OperatingTenantId AND s.PartnerSellerId=l.PartnerSellerId WHERE l.OperatingTenantId=@tenant AND l.ProductId=@product;", connection, transaction);
        command.Parameters.AddWithValue("@tenant", tenantId);
        command.Parameters.AddWithValue("@product", productId);
        await using var reader = await command.ExecuteReaderAsync(token);
        if (!await reader.ReadAsync(token)) return new("OWNED", null, null, null);
        if (reader.GetString(1) != "APPROVED")
            throw new BusinessRuleException("A partner product is not approved for marketplace fulfilment.");
        if (reader.IsDBNull(2)) throw new BusinessRuleException("The partner seller is not mapped to an eligible marketplace city.");
        return new("PARTNER", reader.GetGuid(0), reader.GetGuid(2), null);
    }

    private static async Task<AgreementTerms> ReadActiveAgreement(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, SellerSource seller, Guid productId, CancellationToken token)
    {
        await using var command = new SqlCommand("""
            SELECT TOP(1) AgreementId,AgreementVersion,CommissionType,CommissionValue,CalculationBasis,
              DiscountResponsibility,DeliveryResponsibility,PackagingResponsibility,PaymentFeeResponsibility,ReturnTreatment
            FROM commerce.PartnerCommissionAgreements WITH(UPDLOCK,HOLDLOCK)
            WHERE OperatingTenantId=@tenant AND PartnerSellerId=@seller AND (ProductId=@product OR ProductId IS NULL)
              AND AgreementStatus='ACTIVE' AND EffectiveFrom<=SYSUTCDATETIME()
              AND (EffectiveTo IS NULL OR EffectiveTo>SYSUTCDATETIME())
            ORDER BY CASE WHEN ProductId=@product THEN 0 ELSE 1 END,AgreementVersion DESC,AgreementId;
            """, connection, transaction);
        command.Parameters.AddWithValue("@tenant", tenantId); command.Parameters.AddWithValue("@seller", seller.PartnerSellerId!.Value);
        command.Parameters.AddWithValue("@product", productId);
        await using var reader = await command.ExecuteReaderAsync(token);
        if (!await reader.ReadAsync(token))
            throw new BusinessRuleException("The partner product has no active approved commercial agreement.");
        return new(reader.GetGuid(0), reader.GetInt32(1), reader.GetString(2), reader.GetDecimal(3), reader.GetString(4),
            reader.GetString(5), reader.GetString(6), reader.GetString(7), reader.GetString(8), reader.GetString(9));
    }

    private static async Task<IReadOnlyCollection<Guid>> ReadCandidateWarehouses(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, SellerSource seller, string pincode, CancellationToken token)
    {
        await using var command = new SqlCommand("""
            SELECT DISTINCT WarehouseId
            FROM commerce.WarehouseStorefrontServiceAreas WITH(UPDLOCK,HOLDLOCK)
            WHERE TenantId=@tenant AND SellerKind=@kind
              AND ISNULL(PartnerSellerId,'00000000-0000-0000-0000-000000000000')=ISNULL(@seller,'00000000-0000-0000-0000-000000000000')
              AND Pincode=@pincode AND IsEnabled=1
            ORDER BY WarehouseId;
            """, connection, transaction);
        command.Parameters.AddWithValue("@tenant", tenantId);
        command.Parameters.AddWithValue("@kind", seller.SellerKind);
        command.Parameters.AddWithValue("@seller", (object?)seller.PartnerSellerId ?? DBNull.Value);
        command.Parameters.AddWithValue("@pincode", pincode);
        var result = new List<Guid>();
        await using var reader = await command.ExecuteReaderAsync(token);
        while (await reader.ReadAsync(token)) result.Add(reader.GetGuid(0));
        return result;
    }

    private static async Task<IReadOnlyCollection<StockBalance>> ReadAvailableBalances(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, Guid warehouseId, Guid productId, CancellationToken token)
    {
        await using var command = new SqlCommand("""
            SELECT InventoryBalanceId,ZoneId,BinId,BatchNo,SerialNo,QuantityAvailable
            FROM inventory.InventoryBalances WITH(UPDLOCK,HOLDLOCK)
            WHERE TenantId=@tenant AND WarehouseId=@warehouse AND ProductId=@product AND QuantityAvailable>0
            ORDER BY ZoneId,BinId,BatchNo,SerialNo,InventoryBalanceId;
            """, connection, transaction);
        command.Parameters.AddWithValue("@tenant", tenantId);
        command.Parameters.AddWithValue("@warehouse", warehouseId);
        command.Parameters.AddWithValue("@product", productId);
        var result = new List<StockBalance>();
        await using var reader = await command.ExecuteReaderAsync(token);
        while (await reader.ReadAsync(token))
            result.Add(new(reader.GetGuid(0), reader.IsDBNull(1) ? null : reader.GetGuid(1),
                reader.IsDBNull(2) ? null : reader.GetGuid(2), reader.IsDBNull(3) ? null : reader.GetString(3),
                reader.IsDBNull(4) ? null : reader.GetString(4), reader.GetDecimal(5)));
        return result;
    }

    private static IReadOnlyCollection<POSItemInput> DeserializeItems(string? itemsJson)
    {
        if (string.IsNullOrWhiteSpace(itemsJson)) throw new BusinessRuleException("The cart items are invalid.");
        try
        {
            using var document = JsonDocument.Parse(itemsJson);
            if (document.RootElement.ValueKind != JsonValueKind.Array) throw new JsonException();
            return JsonSerializer.Deserialize<POSItemInput[]>(itemsJson, ItemJsonOptions) ?? [];
        }
        catch (JsonException)
        {
            throw new BusinessRuleException("The cart items are invalid. Refresh your cart and try again.");
        }
    }

    private static async Task<POSPostResult> PostHeldInvoice(SqlConnection connection, SqlTransaction transaction,
        Guid tenantId, POSPostRequest request, CancellationToken token)
    {
        await using var command = new SqlCommand("sales.POS_PostInvoice", connection, transaction) { CommandType = CommandType.StoredProcedure };
        Add(command, "@TenantId", tenantId);
        Add(command, "@CounterId", request.CounterId); Add(command, "@ShiftId", request.ShiftId);
        Add(command, "@CustomerId", request.CustomerId); Add(command, "@WarehouseId", request.WarehouseId);
        Add(command, "@SalesPersonId", request.SalesPersonId); Add(command, "@ItemsJson", request.ItemsJson);
        Add(command, "@PaymentsJson", "[]"); Add(command, "@BillDiscount", request.BillDiscount);
        Add(command, "@RoundOff", request.RoundOff); Add(command, "@Remarks", request.Remarks);
        Add(command, "@Status", "HELD"); Add(command, "@InterState", request.InterState);
        Add(command, "@DiscountAuthorizedBy", request.DiscountAuthorizedBy); Add(command, "@CreatedBy", request.User);
        Add(command, "@DeliveryCharge", request.DeliveryCharge); Add(command, "@PromotionDiscountAmount", request.PromotionDiscountAmount);
        Add(command, "@AppliedPromotionId", request.AppliedPromotionId); Add(command, "@AppliedPromotionName", request.AppliedPromotionName);
