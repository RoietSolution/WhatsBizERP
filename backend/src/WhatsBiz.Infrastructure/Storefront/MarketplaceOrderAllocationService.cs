    private static async Task<IReadOnlyCollection<InvoiceItemRef>> ReadInvoiceItems(SqlConnection connection,
        SqlTransaction transaction, Guid invoiceId, CancellationToken token)
    {
        var result = new List<InvoiceItemRef>();
        await using var command = new SqlCommand("SELECT InvoiceItemId,ProductId FROM sales.SalesInvoiceItems WITH(UPDLOCK,HOLDLOCK) WHERE InvoiceId=@invoice ORDER BY ProductId,InvoiceItemId;", connection, transaction);
        command.Parameters.AddWithValue("@invoice", invoiceId);
