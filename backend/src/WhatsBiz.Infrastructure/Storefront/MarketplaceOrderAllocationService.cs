    private static async Task ReserveAllocation(SqlConnection connection, SqlTransaction transaction, Guid tenantId,
        Guid allocationId, DateTimeOffset expiresAt, string? user, CancellationToken token)
    {
        await using var command = new SqlCommand("commerce.Marketplace_ReserveAllocation", connection, transaction) { CommandType = CommandType.StoredProcedure };
        command.Parameters.AddWithValue("@TenantId", tenantId); command.Parameters.AddWithValue("@AllocationId", allocationId);
        command.Parameters.AddWithValue("@ExpiresAt", expiresAt);
        command.Parameters.AddWithValue("@ReservationIdempotencyKey", $"{allocationId:N}:RESERVE");
        command.Parameters.AddWithValue("@CreatedBy", (object?)user ?? DBNull.Value);
        await using var reader = await command.ExecuteReaderAsync(token);
        if (!await reader.ReadAsync(token) || reader.GetString(reader.GetOrdinal("ReservationStatus")) != "RESERVED")
            throw new BusinessRuleException("Warehouse stock could not be reserved. Refresh your cart and try again.");
    }

